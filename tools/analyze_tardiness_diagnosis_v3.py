"""Renders results/tardiness_diagnosis_v3.md from results/tardiness_diagnosis_v3/part_a_<size>.json
(tools/tardiness_diagnosis_v3.py; docs/tardiness_diagnosis_protocol_v3.md). Code quotes are read from the source files
at render time and located by content, so a quote can never drift from the code it describes."""
from __future__ import annotations
import json
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
SIZES = ("10x5", "20x10")


def quote(rel, first, n):
    """The n lines of `rel` starting at the first line containing `first`, with their line numbers."""
    lines = (REPO / rel).read_text().splitlines()
    i = next(k for k, l in enumerate(lines) if first in l)
    body = "\n".join(lines[i:i + n])
    return f"`{rel}:{i + 1}-{i + n}`\n\n```python\n{body}\n```"


def f1(x):
    return f"{x:.1f}"


def pct(x):
    return f"{100 * x:.0f}%"


def render(out: Path, quick=False):
    R = {s: json.loads((out / f"part_a_{s}.json").read_text()) for s in SIZES if (out / f"part_a_{s}.json").exists()}
    L = ["# Why is DANIEL-T so far from CP-SAT? Tardiness diagnosis, benchmark v3", "",
         "Protocol: `docs/tardiness_diagnosis_protocol_v3.md`. Generated by `tools/analyze_tardiness_diagnosis_v3.py` from "
         "`results/tardiness_diagnosis_v3/` (`tools/tardiness_diagnosis_v3.py`). No training was run. Evaluation split "
         "only; the reserved final-test sets were never loaded.", ""]
    if quick:
        L += ["**SMOKE OUTPUT (3 instances, tiny search): not results.**", ""]

    # ------------------------------------------------------------------ A1
    L += ["## 1. The reward: dense, not sparse", "",
          "**Plain answer: the tardiness reward is dense.** It is not paid only when a late job finishes. At every step "
          "the environment estimates total tardiness from each job's *lower-bound* completion time, and the reward is "
          "minus the change in that estimate. This is the same construction as DANIEL's makespan reward, which is minus "
          "the change in the largest lower-bound completion time. So **Part B (a dense tardiness reward option) was "
          "skipped**: the reward it would add already exists.", "",
          "The estimate (a potential) is total tardiness evaluated on each job's current completion-time lower bound:", "",
          quote("daniel/objectives.py", "def tardiness_potential(", 8), "",
          "At every step the environment takes the change in that estimate as the tardiness reward. The makespan "
          "potential is computed in the same place:", "",
          quote("daniel/fjsp_env_same_op_nums.py", "tardiness_score = self.compute_tardiness_score()", 16), "",
          "Both potentials start from zero, so the episode's return is exactly minus the final value:", "",
          quote("daniel/fjsp_env_same_op_nums.py", "# Tardiness shaping starts from a potential of ZERO", 6), "",
          "With goal `t` (DANIEL-T), only the tardiness term is weighted (w_t = 1). It is converted back to raw time and "
          "divided by the size's Tref:", "",
          quote("daniel/objectives.py", "def step_reward(self, mk_potential_delta", 10), "",
          "**What the lower bound is.** Before any scheduling, each operation's lower-bound completion time is the sum of "
          "its job's minimum processing times so far. When an operation is scheduled, its job's later lower bounds move by "
          "the delay (`op_ct_lb[mask1] += diff`). The bound ignores waiting for machines until the job's own next "
          "operation is placed. The consequence: a decision that delays *another* job is charged to that other job only "
          "when it is scheduled. The reward is dense, but its credit for a decision can arrive later.", ""]
    rows = []
    for s, r in R.items():
        a = r["a1"]
        rows.append(f"| {s} | {a['steps']} | {pct(a['tardiness_reward_nonzero_share'])} | "
                    f"{pct(a['late_job_completion_share'])} | {pct(a['makespan_reward_nonzero_share'])} | "
                    f"{pct(a['tardiness_return_first_half_share'])} | {pct(a['makespan_return_first_half_share'])} |")
    L += ["**Measured** along DANIEL-T s111's greedy schedules (the subset in section 4, replayed through the environment "
          "with goal `t`):", "",
          "| Size | Steps per episode | Steps with a non-zero tardiness reward | Steps where a late job finishes (when a sparse reward would pay) | Steps with a non-zero makespan reward | Share of the tardiness return paid in the first half of the episode | Same, makespan |",
          "|---|---|---|---|---|---|---|", *rows, "",
          "The tardiness reward is non-zero on two to three times as many steps as a sparse reward would be, and at least "
          "as often as the makespan reward. Almost all of it arrives in the second half of the episode, because the "
          "lower-bound estimate passes a due date only late in the schedule. The reward is dense in form, but it is "
          "back-loaded: the early decisions that cause lateness are paid for many steps later.", ""]

    # ------------------------------------------------------------------ A2
    L += ["## 2. What the network sees about due dates", "",
          "Due dates are divided by the fixed time scale 99, the same scale as processing times:", "",
          quote("daniel/fjsp_env_same_op_nums.py", "self.due_dates = due / self.pt_upper_bound", 1), "",
          "**Operation features (2 of 12).** These are given per operation, repeated for every operation of the same job:", "",
          quote("daniel/fjsp_env_same_op_nums.py", "est, work, _, _ = self.v2_job_state()", 5), "",
          "| Feature | Definition (all divided by 99) | Normalisation |",
          "|---|---|---|",
          "| slack | d_j − EST_j − W_j: the due date minus the earliest start of the job's next operation minus the job's remaining minimum work | z-score per instance at every step, over the operations not yet finished (`norm_op_features`) |",
          "| time to due | d_j − EST_j | the same z-score |", "",
          "**Pair feature (1 of 10).** This is given per (job, machine) candidate pair:", "",
          quote("daniel/fjsp_env_same_op_nums.py", "late = np.maximum(0.0, pair_start", 3), "",
          "| Feature | Definition (divided by 99) | Normalisation |",
          "|---|---|---|",
          "| lateness | max(0, start of the pair + its processing time + the job's remaining minimum work after it − d_j); for a finished job, its actual lateness | none: fed to the actor as is |", "",
          "**Not seen:** the due date itself, the current time and total or current tardiness. The machine features carry "
          "no due-date information.", "",
          "**One consequence of the z-score.** It removes the sign and scale of slack and time to due. After it, the "
          "network can tell which job has less slack than the others, but not whether any job is already late. Only the "
          "pair lateness feature keeps absolute units, and it is zero for every pair that is not yet estimated late.", ""]

    # ------------------------------------------------------------------ A3
    L += ["## 3. The gap in plain units (all 100 evaluation instances)", ""]
    for s, r in R.items():
        a3 = r["a3"]; rule = a3["rule"]["mean"]
        g, sm = a3["daniel_greedy"], a3["daniel_sample100"]
        cp = a3["cpsat"]
        L += [f"### {s}", "",
              "| Method | Total tardiness | Share of the MWKR+ECT rule's tardiness | Jobs late | Instances with zero tardiness |",
              "|---|---|---|---|---|",
              f"| MWKR+ECT reference rule | {f1(rule)} | 100% | {pct(a3['rule']['tardy_share'])} | {a3['rule']['zero']} / {a3['n']} |",
              f"| DANIEL-T greedy (mean of 3 seeds; {', '.join(f1(p['mean']) for p in g['per_seed'])}) | {f1(g['mean'])} | "
              f"{pct(g['mean'] / rule)} | {pct(g['tardy_share'])} | {np.mean([p['zero'] for p in g['per_seed']]):.1f} / {a3['n']} |",
              f"| DANIEL-T best of 100 samples (mean of 3 seeds; {', '.join(f1(p['mean']) for p in sm['per_seed'])}) | "
              f"{f1(sm['mean'])} | {pct(sm['mean'] / rule)} | {pct(sm['tardy_share'])} | "
              f"{np.mean([p['zero'] for p in sm['per_seed']]):.1f} / {a3['n']} |",
              f"| CP-SAT single-objective tardiness ({cp['optimal']} / {a3['n']} proven optimal) | {f1(cp['mean'])} | "
              f"{pct(cp['mean'] / rule)} | {pct(cp['tardy_share'])} | {cp['zero']} / {a3['n']} |", ""]
        rel = (g["mean"] - cp["mean"]) / cp["mean"]
        L += [f"**Why a percentage gap is misleading here.** CP-SAT's mean is {f1(cp['mean'])}, and on {cp['zero']} of "
              f"{a3['n']} instances the optimum is exactly 0. A gap relative to the optimum, (DANIEL − CP-SAT) / CP-SAT, "
              f"comes to {100 * rel:,.0f}% on the means and is undefined (division by zero) on those {cp['zero']} "
              "instances. Near zero, a few minutes of lateness becomes hundreds of percent. Measured against a scale that "
              f"does not vanish, such as the rule's tardiness, DANIEL-T greedy removes {pct(1 - g['mean'] / rule)} of the "
              f"rule's tardiness and CP-SAT removes {pct(1 - cp['mean'] / rule)}.", ""]

    # ------------------------------------------------------------------ A4
    L += ["## 4. Splitting the gap: the no-waiting rule against learning", "",
          "**Instances:** the first 20 evaluation instances per size. Every one has a CP-SAT single-objective tardiness "
          "result.", "",
          "**What \"without waiting\" means.** DANIEL's action mask allows only the pairs that can start at the earliest "
          "possible start time (`unavailable_pairs = pair_free_time > next_schedule_time`). So DANIEL can never leave a "
          "machine idle on purpose to keep it free for a more urgent job (a non-delay schedule). CP-SAT has no such "
          "restriction.", "",
          "**(b) is found by a time-limited search.**",
          "- **Method:** random-key genetic search over schedules decoded by the same mask, in the environment's own "
          "arithmetic. Every (operation, machine) pair has a key, and at each step the allowed pair with the smallest key "
          "is chosen. Every no-waiting schedule can be reached this way.",
          "- **Settings:** population 200 per instance, 20 kept each generation, uniform crossover per operation, 5% of "
          "keys mutated by N(0, 0.1), 5% random newcomers, seed 2026.",
          "- **Limit:** a fixed generation budget (below).",
          "- **Seeds in the starting population:** the three rules, CP-SAT's own schedule order decoded through the mask, "
          "and DANIEL-T's committed greedy and best-of-100 schedules for all three seeds. The result is therefore never "
          "worse than DANIEL-T.",
          "- **What (b) is:** an upper bound on the best no-waiting tardiness, not a proven optimum.", "",
          "**Checks:** every schedule in the table was replayed through the real environment and re-scored by the "
          "independent scorer, and all agree. The search's decoder allows exactly the environment's pairs at every step "
          "(`tests/test_tardiness_diagnosis_v3.py`).", ""]
    for s, r in R.items():
        a4 = r["a4"]
        ref = a4["reference_rule"]["mean"]
        n = len(r["keys"])

        def row(label, d, ms=True):
            return (f"| {label} | {f1(d['mean'])} | {pct(d['mean'] / ref)} | "
                    f"{pct(d['tardy_share']) if 'tardy_share' in d else '-'} | {d['zero']} / {n} | "
                    f"{f1(d['makespan']) if ms and 'makespan' in d else '-'} |")

        def drow(label, d):
            ps = d["per_seed"]
            return (f"| {label} (seeds {', '.join(f1(p['mean']) for p in ps)}) | {f1(d['mean'])} | "
                    f"{pct(d['mean'] / ref)} | {pct(d['tardy_share'])} | "
                    f"{np.mean([p['zero'] for p in ps]):.1f} / {n} | - |")
        sr = a4["search"]
        L += [f"### {s} ({n} instances)", "",
              "| | Method | Mean tardiness | Share of MWKR+ECT reference | Jobs late | Zero-tardiness instances | Mean makespan |",
              "|---|---|---|---|---|---|---|"]
        body = [("a", row(f"CP-SAT optimum ({a4['cpsat']['optimal']} / {n} proven optimal, others best-known)", a4["cpsat"])),
                ("b", row(f"Best found without waiting (search, {sr['settings']['generations']} generations, "
                          f"{sr['seconds'] / 60:.0f} min)", sr)),
                ("b", row("CP-SAT's own order, decoded without waiting", a4["cpsat_order_in_env"])),
                ("c", row("EDD+ECT without waiting", a4["env_EDD+ECT"])),
                ("c", row("MWKR+ECT without waiting", a4["env_MWKR+ECT"])),
                ("c", row("Least slack (LST)+ECT without waiting", a4["env_LST+ECT"])),
                ("c", row("EDD+ECT, waiting allowed (context)", a4["active_EDD+ECT"], ms=False)),
                ("c", row("MWKR+ECT, waiting allowed: the benchmark reference (context)", a4["reference_rule"], ms=False)),
                ("d", drow("DANIEL-T greedy", a4["daniel_greedy"])),
                ("d", drow("DANIEL-T best of 100 samples", a4["daniel_sample100"]))]
        L += [f"| {k} {b[1:]}" for k, b in body] + [""]
        A, Bv = a4["cpsat"]["mean"], sr["mean"]
        Dg, Ds = a4["daniel_greedy"]["mean"], a4["daniel_sample100"]["mean"]
        L += ["**The split** (mean tardiness):", "",
              "| | DANIEL-T greedy | DANIEL-T best of 100 |", "|---|---|---|",
              f"| Total gap to CP-SAT (d − a) | {f1(Dg - A)} | {f1(Ds - A)} |",
              f"| From the no-waiting rule (b − a) | {f1(Bv - A)} ({pct((Bv - A) / (Dg - A))}) | {f1(Bv - A)} ({pct((Bv - A) / (Ds - A))}) |",
              f"| From learning (d − b) | {f1(Dg - Bv)} ({pct((Dg - Bv) / (Dg - A))}) | {f1(Ds - Bv)} ({pct((Ds - Bv) / (Ds - A))}) |", ""]
        tr = sr["trajectory"]; G = len(tr)
        src = {}
        for x in a4["best_seed_source"]:
            src[x] = src.get(x, 0) + 1
        L += [f"**Search notes.**",
              f"- The best seed (before any search) averaged {f1(a4['best_seed']['mean'])}. Sources of the best seed: "
              f"{', '.join(f'{k} {v}' for k, v in sorted(src.items(), key=lambda kv: -kv[1]))}.",
              f"- The search beat every seed on {sr['beat_every_seed']} of {n} instances.",
              f"- Mean best tardiness after {G // 4}, {G // 2} and {G} generations: {f1(tr[G // 4 - 1])}, "
              f"{f1(tr[G // 2 - 1])} and {f1(tr[-1])}. "
              f"The second half of the budget improved it by {pct((tr[G // 2 - 1] - tr[-1]) / tr[G // 2 - 1])}. A slowing "
              "search is not evidence of being near the best possible, so (b) is an upper bound only.",
              f"- The DANIEL-T schedules were reproduced exactly through the mask: "
              f"{', '.join(f'{k} {v}/{n}' for k, v in a4['daniel_schedules_reproduced'].items())}.", ""]

    # ------------------------------------------------------------------ verdict
    L += ["## Verdict", ""]
    for s, r in R.items():
        a4 = r["a4"]; A, Bv = a4["cpsat"]["mean"], a4["search"]["mean"]
        Dg, Ds = a4["daniel_greedy"]["mean"], a4["daniel_sample100"]["mean"]
        L.append(f"- **{s}:** of the greedy gap of {f1(Dg - A)}, at most {pct((Bv - A) / (Dg - A))} is due to the "
                 f"no-waiting rule and at least {pct((Dg - Bv) / (Dg - A))} to learning. With best of 100 samples the "
                 f"shares are {pct((Bv - A) / (Ds - A))} and {pct((Ds - Bv) / (Ds - A))}.")
    L += ["", "VERDICT_PLACEHOLDER", "",
          "Single search seed and the committed specialists only: numbers only, no significance claims.", "",
          "## Files", "",
          "- `tools/tardiness_diagnosis_v3.py`: computation (`run`); `tools/analyze_tardiness_diagnosis_v3.py`: this report.",
          "- `results/tardiness_diagnosis_v3/part_a_<size>.json`: every number above, with per-instance values and the "
          "SHA-256 of each committed evaluation file read.",
          "- `tests/test_tardiness_diagnosis_v3.py`: mask equivalence, exact replay, rule choices.",
          "- `docs/tardiness_diagnosis_protocol_v3.md`: the protocol, fixed before the run.", ""]
    text = "\n".join(L)
    verdict = (out / "verdict.md")
    text = text.replace("VERDICT_PLACEHOLDER", verdict.read_text().strip() if verdict.exists() else
                        "_(verdict to be written from the numbers above)_")
    dest = out.parent / (out.name + ".md")
    dest.write_text(text)
    print(f"wrote {dest}")
