"""Renders results/tardiness_features_v3.md (docs/tardiness_features_protocol_v3.md): the tardiness specialist with
lateness inputs against the committed one. Reads the committed specialist's evaluation and run record and the
tardiness diagnosis (all read-only) and the new run's outputs (scripts/run_tardiness_features_v3.sh).

    python tools/analyze_tardiness_features_v3.py [--smoke]
"""
from __future__ import annotations
import argparse, hashlib, json
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
SIZE, SEED = "10x5", 111
CUR_NAME = f"{SIZE}+mix+bv3_spec_t_s{SEED}"
BASE = REPO / "results" / "baselines_v3"
DIAG = REPO / "results" / "tardiness_diagnosis_v3" / f"part_a_{SIZE}.json"
CUR, NEW = "Tardiness specialist, current", "Tardiness specialist, with lateness inputs"


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def npz(p):
    d = np.load(p)
    return {k: d[k] for k in d.files}


def f1(x):
    return "-" if x is None else f"{x:.1f}"


def pct(x):
    return "-" if x is None else f"{100 * x:.0f}%"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--smoke", action="store_true")
    a = ap.parse_args()
    sfx = "_smoke" if a.smoke else ""
    res = REPO / "results" / f"tardiness_features_v3{sfx}"
    ckpt = REPO / "checkpoints" / f"tardiness_features_v3{sfx}"
    new_name = f"{SIZE}+mix+bv3_tlate{'s' if a.smoke else ''}_s{SEED}"
    split = "development" if a.smoke else "evaluation"
    diag = json.loads(DIAG.read_text())

    # ------------------------------------------------------------------ data
    cur_g = npz(BASE / "eval" / f"evaluation_{SIZE}" / f"{CUR_NAME}.npz")
    cur_s = npz(BASE / "eval" / f"evaluation_{SIZE}" / f"{CUR_NAME}_sample100.npz")
    edir = res / "eval" / f"{split}_{SIZE}"
    new_g = npz(edir / f"{new_name}.npz")
    smp = sorted(edir.glob(f"{new_name}_sample*.npz"))
    new_s = npz(smp[0]) if smp else None
    keys = list(diag["keys"])                                   # the diagnosis's 20 instances
    rule_all = np.asarray(diag["a3"]["rule"]["per_instance"])   # MWKR+ECT reference rule, all 100, loader order
    seeds3 = {m: diag["a3"][f"daniel_{m}"] for m in ("greedy", "sample100")}

    def summ(d, idx=None):
        if d is None:
            return None
        sel = np.arange(len(d["keys"])) if idx is None else idx
        return {"t": float(d["tardiness"][sel].mean()), "late": float(d["tardy_share"][sel].mean())}

    comparable = list(new_g["keys"]) == list(cur_g["keys"])     # False only for the smoke test (development split)
    rule_mean = float(rule_all.mean())

    L = ["# Does absolute lateness information help the tardiness specialist? Benchmark v3", "",
         "Protocol: `docs/tardiness_features_protocol_v3.md`. Generated by `tools/analyze_tardiness_features_v3.py`. "
         "Single training seed (111): numbers only, no significance claims. Evaluation split only; the reserved "
         "final-test sets were never loaded.", ""]
    if a.smoke:
        L += ["**SMOKE OUTPUT (5 updates, 3 development instances): not results. The comparison tables are empty "
              "because the smoke test evaluates on the development split.**", ""]
    L += ["## The change", "",
          f"**\"{NEW}\"** is the committed tardiness specialist's training run (\"{CUR}\", DANIEL-T s111) with one "
          "option on, `--lateness_inputs on`. It adds five per-job features to every operation's input, all in fixed "
          "units (time / 99, the benchmark's time scale) and not rescaled per step:",
          "- current time;",
          "- due date − current time, signed (negative means overdue);",
          "- absolute slack (due date − earliest start − remaining minimum work);",
          "- an already-late flag;",
          "- a will-be-late flag.", "",
          "**Where they enter the network.** The operation features feed the first operation-attention layer and the "
          "edge input of the first machine-attention layer. Those 8 weight matrices grow from 12 × 32 to 17 × 32 "
          "(+1,280 parameters, 29,602 → 30,882), and nothing else changes. The 12 existing features are unchanged and "
          "still rescaled per step.", "",
          "**With the option off,** a 5-update run gives bit-identical weights and validation values before and after "
          "the change.", "",
          "**Two differences from the committed run** are unavoidable or outside the run:",
          "- The first-layer shape differs, so every layer's random initialisation differs. The training-instance "
          "stream is the same.",
          "- The committed run shared the PC with CP-SAT, on separate CPUs, so wall-clock is comparable only "
          "approximately.", ""]

    # ------------------------------------------------------------------ evaluation, 100 instances
    L += [f"## Evaluation ({len(new_g['keys'])} {split} instances)", "",
          "| Specialist | Mode | Mean tardiness | Share of the MWKR+ECT rule's tardiness | Jobs late |",
          "|---|---|---|---|---|"]
    for mode, cd, nd in (("greedy", cur_g, new_g), ("best of 100 samples", cur_s, new_s)):
        c, n = summ(cd), summ(nd)
        L.append(f"| {CUR} (seed 111) | {mode} | {f1(c['t'])} | {pct(c['t'] / rule_mean)} | {pct(c['late'])} |")
        s3 = seeds3["greedy" if mode == "greedy" else "sample100"]
        L.append(f"| {CUR} (mean of seeds 111/222/333, context) | {mode} | {f1(s3['mean'])} | "
                 f"{pct(s3['mean'] / rule_mean)} | {pct(s3['tardy_share'])} |")
        if comparable and n:
            L.append(f"| **{NEW}** (seed 111) | {mode} | **{f1(n['t'])}** | {pct(n['t'] / rule_mean)} | {pct(n['late'])} |")
        elif n:
            L.append(f"| {NEW} (seed 111, smoke: development split, not comparable) | {mode} | {f1(n['t'])} | - | "
                     f"{pct(n['late'])} |")
    L += ["", f"The MWKR+ECT reference rule's mean tardiness on these instances is {f1(rule_mean)}.", ""]

    # ------------------------------------------------------------------ gap split, 20 instances
    a4 = diag["a4"]
    A, Bv = a4["cpsat"]["mean"], a4["search"]["mean"]
    cur3 = a4["daniel_greedy"]["mean"]
    idx = [list(cur_g["keys"]).index(k) for k in keys]
    cur111 = summ(cur_g, idx)["t"]
    L += [f"## On the diagnosis's {len(keys)} instances (`{Path(keys[0]).stem}` to `{Path(keys[-1]).stem}`)", "",
          "| | Method | Mean tardiness |", "|---|---|---|",
          f"| a | CP-SAT optimum | {f1(A)} |",
          f"| b | Best found without waiting (search) | {f1(Bv)} |",
          f"| d | {CUR}, greedy (mean of 3 seeds; seed 111: {f1(cur111)}) | {f1(cur3)} |",
          f"| d | {CUR}, best of 100 (mean of 3 seeds) | {f1(a4['daniel_sample100']['mean'])} |"]
    if comparable:
        ng, ns = summ(new_g, idx)["t"], (summ(new_s, idx)["t"] if new_s else None)
        L += [f"| **new** | **{NEW}, greedy** | **{f1(ng)}** |",
              f"| **new** | **{NEW}, best of 100** | **{f1(ns)}** |", "",
              "**Share of the learning gap closed,** (current − new) / (current − 50.5):", "",
              "| Current | Greedy |", "|---|---|",
              f"| 3-seed mean, {f1(cur3)} (as specified) | {pct((cur3 - ng) / (cur3 - Bv))} |",
              f"| seed 111, {f1(cur111)} (same seed as the new run) | {pct((cur111 - ng) / (cur111 - Bv))} |", "",
              "The 50.5 is an upper bound on the best tardiness without waiting, from a search that started from the "
              "current specialist's schedules. A new result below 50.5 would make the share exceed 100%.", ""]
    else:
        L += ["| new | (smoke: not evaluated on these instances) | - |", ""]

    # ------------------------------------------------------------------ training
    cs = json.loads((BASE / "runs" / CUR_NAME / "status.json").read_text())
    cm = json.loads((BASE / "runs" / CUR_NAME / "run_meta.json").read_text())
    ns_ = json.loads((res / "runs" / new_name / "status.json").read_text())
    npj = res / "runs" / new_name / "process.json"
    nproc = json.loads(npj.read_text())["process_seconds"] if npj.exists() else None
    L += ["## Training", "",
          "| Specialist | Update of best | Stop update | Status | Best validation value | Training wall-clock (h) | Process wall-clock (h) |",
          "|---|---|---|---|---|---|---|",
          f"| {CUR} (seed 111) | {cs['best_update']} | {cs['update']} | {cs['status']} | {cs['best_value']:.4f} | "
          f"{cs['train_seconds'] / 3600:.2f} | {cm['process_seconds'] / 3600:.2f} |",
          f"| {NEW} (seed 111) | {ns_['best_update']} | {ns_['update']} | {ns_['status']} | {ns_['best_value']:.4f} | "
          f"{ns_['train_seconds'] / 3600:.2f} | {'-' if nproc is None else f'{nproc / 3600:.2f}'} |", "",
          "- **Best validation value:** mean tardiness / Tref on the validation split (lower is better), the "
          "specialists' selection metric.",
          "- **Training wall-clock:** time inside the update loop, validation included.",
          "- **Process wall-clock:** also includes start-up and checkpoint I/O.",
          "- **Stopping rule:** at least 1,000 updates; stop once the best value has improved by less than 0.5% over "
          "the last 1,000 updates; cap 5,000.", ""]

    # ------------------------------------------------------------------ merging / distillation
    L += ["## Consequence for merging and distillation", "",
          "The new specialist's operation input has 17 features against the current specialists' 12. Its first "
          "attention layers therefore have 17 × 32 weight matrices where the makespan and carbon specialists have "
          "12 × 32. It cannot be weight-averaged, task-arithmetic-merged or TIES-merged with them, and the "
          "merge-then-fine-tune and distillation pipelines (which load every source with the 12-feature schema) refuse "
          "it. If the change is adopted, one of the following is needed:", "",
          "1. **Retrain the makespan and carbon specialists with `--lateness_inputs on`** (all sizes and seeds). Every "
          "specialist then shares the 17-feature schema. This is the clean option, but it means new specialists and "
          "new merges, and the MO network and its preference-conditioned schema would need the same option.",
          "2. **Pad the current specialists.** Add five zero rows to their 8 first-layer matrices. A zero row makes a "
          "network ignore that input exactly, so their behaviour is unchanged, the same device the merges already use "
          "for the preference columns. They can then be merged with the new specialist. Their padded rows are zero "
          "rather than learned, so a merge dilutes the new specialist's use of the lateness inputs.",
          "3. **For distillation only:** the student uses the 17-feature input, and each teacher receives the first 12 "
          "columns, which are unchanged. This needs the distillation code to slice the teachers' inputs; no "
          "retraining is required.", ""]

    # ------------------------------------------------------------------ files
    sums = json.loads((ckpt / "SHA256SUMS.json").read_text()) if (ckpt / "SHA256SUMS.json").exists() else {}
    L += ["## Files and hashes", "",
          f"- **Checkpoints** (`{ckpt.relative_to(REPO)}/`, SHA-256 in `SHA256SUMS.json`):"]
    for k, v in sums.items():
        ok = sha(ckpt / k) == v
        L.append(f"  - `{k}`: `{v}`{'' if ok else ' **MISMATCH**'}")
    L += [f"- **Current specialist read:** `checkpoints/specialists_v3/{CUR_NAME}.pth` "
          f"(`{sha(REPO / 'checkpoints' / 'specialists_v3' / f'{CUR_NAME}.pth')}`), with its evaluation in "
          "`results/baselines_v3/eval/` and the diagnosis in `results/tardiness_diagnosis_v3/`.",
          f"- **Run record:** `{(res / 'runs' / new_name).relative_to(REPO)}/`; **evaluation:** "
          f"`{edir.relative_to(REPO)}/`.",
          "- **Code:** `--lateness_inputs` (`daniel/params.py`, `daniel/fjsp_env_same_op_nums.py: lateness_op_features`, "
          "`daniel/feature_schemas.py`), `scripts/run_tardiness_features_v3.sh`, "
          "`tests/test_tardiness_features_v3.py`.", ""]
    dest = REPO / "results" / f"tardiness_features_v3{sfx}.md"
    dest.write_text("\n".join(L))
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
