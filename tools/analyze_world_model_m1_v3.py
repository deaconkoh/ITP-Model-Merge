"""Renders results/world_model_m1_v3.md (docs/world_model_m1_protocol_v3.md) from results/world_model_m1_v3/ and applies
the outcome rule frozen in configs/world_model_m1_v3.json.

    python tools/analyze_world_model_m1_v3.py [--smoke]
"""
from __future__ import annotations
import argparse, json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OBJ = ("final makespan", "carbon", "tardiness")
WM, RAND, BASE, MSPEC = ("world-model trunk", "random initialisation (seed 111)", "equal-weight shared base",
                         "makespan specialist (context only)")


def outcome(san, prb, rule):
    """Returns (outcome, clause, details) by the frozen rule."""
    loses = [g for g, v in san["groups"].items() if v["world_model_loses"]]
    wm = prb["trunks"][WM][rule["probe"]]["mae_mean"]
    rnd = prb["trunks"][RAND][rule["probe"]]["mae_mean"]
    base = prb["trunks"][BASE][rule["probe"]]["mae_mean"]
    beats_random = [o for o, a, b in zip(OBJ, wm, rnd) if a < b]
    rel = [(a - b) / b for a, b in zip(wm, base)]                                  # negative = world model better
    better = [o for o, r in zip(OBJ, rel) if r <= -rule["pass_margin"]]
    worse = [o for o, r in zip(OBJ, rel) if r > rule["max_worse"]]
    det = {"sanity_groups_lost": loses, "beats_random_on": beats_random,
           "relative_to_shared_base": dict(zip(OBJ, rel)), "better_by_5pct": better, "worse_by_over_5pct": worse}
    if len(loses) >= rule["fail_sanity_groups"]:
        return "FAIL", (f"the world model loses to the mean or shortcut predictor on {len(loses)} of 3 outcome groups "
                        f"({', '.join(loses)})"), det
    if not beats_random:
        return "FAIL", "the world-model probe is not better than the random trunk's on any objective", det
    if len(better) >= rule["pass_min_objectives"] and not worse:
        return "PASS", (f"sanity passes ({len(loses)} group lost) and the world-model probe error is at least 5% lower "
                        f"than the shared base's on {len(better)} of 3 objectives ({', '.join(better)}), none more than "
                        "5% worse"), det
    why = []
    if len(better) < rule["pass_min_objectives"]:
        why.append(f"at least 5% better than the shared base on only {len(better)} objective(s)")
    if worse:
        why.append(f"more than 5% worse than the shared base on {', '.join(worse)}")
    return "INCONCLUSIVE", "neither FAIL nor PASS: " + "; ".join(why), det


def pm(m, s, f="{:.4f}"):
    return f"{f.format(m)} ± {f.format(s)}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--smoke", action="store_true")
    a = ap.parse_args()
    sfx = "_smoke" if a.smoke else ""
    res = REPO / "results" / f"world_model_m1_v3{sfx}"
    data = REPO / "data" / f"world_model_m1_v3{sfx}"
    ckpt = REPO / "checkpoints" / f"world_model_m1_v3{sfx}"
    cfg = json.loads((REPO / "configs" / "world_model_m1_v3.json").read_text())
    run = {**cfg, **cfg["smoke"]} if a.smoke else cfg
    tm = json.loads((data / "train" / "meta.json").read_text())
    vm = json.loads((data / "val" / "meta.json").read_text())
    pt = json.loads((res / "pretrain.json").read_text())
    san = json.loads((res / "sanity.json").read_text())
    prb = json.loads((res / "probe.json").read_text())
    oc, clause, det = outcome(san, prb, cfg["rule"])
    scale = (run["t_norm"], run["e_norm"] * 5, run["t_ref"])
    L = ["# World-model trunk, Milestone 1 (10x5): does predictive pretraining teach the trunk transferable factory knowledge?", "",
         "Protocol: `docs/world_model_m1_protocol_v3.md`. Generated by `tools/analyze_world_model_m1_v3.py`. "
         "**Single pretraining seed: exploratory evidence only.** No specialists, merging or RL. The evaluation split "
         "and the reserved final-test sets were never used.", ""]
    if a.smoke:
        L += ["**SMOKE OUTPUT (tiny data, 2 epochs, 1 probe seed): not results.**", ""]
    L += [f"## Outcome: **{oc}**", "", f"Rule that decided it: {clause}.", "",
          "The rule was fixed before the run (`configs/world_model_m1_v3.json`; MLP probe, mean over probe seeds):",
          "- **FAIL:** the world model loses to the mean or shortcut predictor on 2 or more of the 3 outcome groups, "
          "OR its probe is not better than the random trunk's on any objective.",
          "- **PASS:** sanity passes AND its probe error is at least 5% lower than the equal-weight shared base's on at "
          "least 2 of 3 objectives, with no objective more than 5% worse.",
          "- **INCONCLUSIVE:** anything else.",
          "- The makespan-specialist trunk is context only and does not enter the rule.", "",
          "**Against the shared base** (MLP probe MAE, (world model − base) / base): "
          + ", ".join(f"{o} {100 * r:+.1f}%" for o, r in det["relative_to_shared_base"].items()) + ".", ""]

    # dataset + cost
    L += ["## Data and cost", "",
          "| | Instances | States | (state, action, continuation) samples | Disk | Time |", "|---|---|---|---|---|---|",
          f"| Pretraining data (SD2 generator stream, seed {run['train_seed']}) | {tm['instances']:,} | {tm['states']:,} | "
          f"about {tm['states'] * run['n_candidates'] * 3:,} | {tm['bytes'] / 1e9:.2f} GB | {tm['seconds'] / 60:.1f} min generation |",
          f"| Check data (v3 validation split) | {vm['instances']} | {vm['states']:,} | - | - | {vm['seconds'] / 60:.1f} min |",
          f"| Pretraining | - | {pt['train_states']:,} train + {pt['holdout_states']:,} hold-out | - | - | "
          f"{pt['seconds'] / 60:.1f} min on {pt['device']} ({pt['epochs_run']} epochs, best {pt['best_epoch']}) |", "",
          f"**Pretraining cost, to count in later efficiency comparisons:** {tm['seconds'] / 3600:.2f} h data "
          f"generation (CPU) + {pt['seconds'] / 3600:.2f} h pretraining (GPU).", "",
          f"**Size.** The size is {run['train_instances']:,} instances rather than an hour of generation. Generation "
          "runs at about 4 s per 500 instances, so an hour would give about 440,000 instances (about 10 GB), more than "
          "the PC's 11 GB of RAM can hold for pretraining. The size was fixed before the run.", "",
          f"**Generator disjointness:** {json.dumps(tm['generator']['forbidden_hashes'])}; "
          f"{tm['generator']['collisions_discarded']} colliding instances discarded.", ""]

    # sanity
    L += ["## Question A: does the world model predict outcomes? (v3 validation instances, the 3 pretraining continuations)", "",
          "Mean absolute error in raw units, lower is better. **Mean:** the training-data mean of each output, per "
          "continuation rule. **Shortcut:**",
          "- *Job completion:* DANIEL's earliest-possible-completion estimate after the action (the environment's "
          "lower bound).",
          "- *Machines:* the committed busy time or energy, plus every unscheduled operation on its fastest or "
          "lowest-energy machine. DANIEL has no machine estimate, so this analogue is used.", "",
          "| Outcome group | World model | Mean predictor | Shortcut | World model loses? |", "|---|---|---|---|---|"]
    for g, v in san["groups"].items():
        L.append(f"| {g} | {v['world model']['mae']:.2f} | {v['mean']['mae']:.2f} | {v['shortcut']['mae']:.2f} | "
                 f"{'yes' if v['world_model_loses'] else 'no'} |")
    L += ["", f"{san['states']:,} states, {san['samples']:,} (state, action, continuation) samples.", ""]

    # transfer
    L += ["## Question B: frozen-trunk transfer to an unseen continuation (least slack + ECT)", "",
          "Each trunk is frozen. A small probe is trained on the 32-value state-action embedding (the candidate "
          "operation's and machine's embeddings plus the two global means; no raw features) to predict the outcome when "
          "the schedule is finished by least-slack + ECT, a rule never seen in pretraining.",
          f"- **Instances:** probe-train {prb['split']['probe_train']} (of which {prb['split']['early_stop']} are used "
          f"for early stopping) and probe-test {prb['split']['probe_test']}, by validation-instance index.",
          f"- **Samples:** {prb['n_fit_samples']:,} fitting, {prb['n_test_samples']:,} test.",
          f"- **Reported:** test MAE in normalised units (makespan / {run['t_norm']:.0f}, carbon / "
          f"{run['e_norm'] * 5:.1f} kg, tardiness / Tref {run['t_ref']:.1f}), mean ± std over {run['probe_seeds']} probe "
          "seeds. Pairwise accuracy is the share of same-state pairs of candidate actions that the probe orders "
          "correctly.", ""]
    for kind, label in (("mlp", "MLP probe (one hidden layer; used by the rule)"), ("linear", "Linear probe")):
        L += [f"### {label}", "",
              "| Trunk | " + " | ".join(f"{o} MAE" for o in OBJ) + " | " + " | ".join(f"{o} pair accuracy" for o in OBJ) + " |",
              "|---|" + "---|" * 6]
        for name, t in prb["trunks"].items():
            r = t[kind]
            L.append(f"| {name} | " + " | ".join(pm(m, s) for m, s in zip(r["mae_mean"], r["mae_std"])) + " | "
                     + " | ".join(pm(m, s, "{:.3f}") for m, s in zip(r["pair_acc_mean"], r["pair_acc_std"])) + " |")
        L.append("")
    r = prb["trunks"][WM]["mlp"]["mae_mean"]
    L += ["**In raw units** (world-model trunk, MLP probe): " + ", ".join(
        f"{o} {m * s:.1f} {'kg' if o == 'carbon' else 'min'}" for o, m, s in zip(OBJ, r, scale)) + ".", ""]

    # design
    L += ["## Design choices", "",
          "- **Trunk:** DANIEL's dual-attention encoder (`feature_exact`), the same architecture and size as the "
          "specialists. The pretrained trunk is saved as a full DANIEL bundle (fresh seed-111 actor and critic, schema "
          "`benchmark_v3_f12_m9_p10`), so it loads into a specialist (`--init_mode exact`) or a preference-conditioned "
          "DANIEL (`--init_mode backbone`).",
          "- **Readout:** the action is read out of the trunk's embeddings exactly as DANIEL's actor reads it: "
          "[chosen job's candidate operation, chosen machine, mean operation, mean machine] embedding.",
          "  - *Job head:* [that job's candidate-operation embedding, action embedding, continuation one-hot] → the job's "
          "completion time; applied to every job.",
          "  - *Machine head:* [that machine's embedding, action embedding, continuation one-hot] → busy time and energy; "
          "applied to every machine.",
          "  - The continuation rule enters only the heads, never the trunk.",
          "- **Training:** Huber loss on targets normalised by fixed constants (times / 990 = 99 × N/M; energy / 133.65 = "
          "13.365 kg × N/M). Adam 1e-3, 256 states per batch with all their candidate actions and continuations. 10% "
          "of the generated instances are held out by instance; early stop after 5 epochs without improvement on that "
          "hold-out, cap 100.",
          "- **Data:**",
          "  - *Behaviour policies* (one per episode, drawn at random): MWKR+ECT, MWKR+MINE, EDD+ECT, uniform random, and "
          "random 30% / MWKR+ECT 70%.",
          f"  - *States:* {run['states_per_episode']} random decision steps per episode.",
          f"  - *Actions:* the behaviour's choice plus up to {run['n_candidates'] - 1} other allowed actions.",
          "  - *Continuations:* each (state, action) is finished by MWKR+ECT, MWKR+MINE and EDD+ECT under DANIEL's "
          "own no-waiting rule, using the tested copy of the environment's transition.",
          "  - *Targets:* exact.",
          "- **Validation data:** every validation instance is run under all five behaviours, every decision step is "
          "used, and every continuation includes least slack + ECT.",
          "- **The random-initialisation trunk** equals the world model's own starting trunk (same seed, same "
          "construction).",
          "- **Single pretraining seed: exploratory evidence only.**", ""]
    sums = json.loads((ckpt / "SHA256SUMS.json").read_text())
    L += ["## Files", "", f"- Checkpoints, `{ckpt.relative_to(REPO)}/` (SHA-256):"]
    L += [f"  - `{k}`: `{v}`" for k, v in sums.items()]
    L += ["- **Comparison trunks:** " + "; ".join(f"`{t['source']}` ({t['sha256'][:12]}…)" for n, t in prb["trunks"].items()
                                       if t["sha256"]),
          f"- **Data:** `{data.relative_to(REPO)}/` (gitignored); shard SHA-256 in `{data.relative_to(REPO)}/train/meta.json`.",
          f"- **Numbers:** `{res.relative_to(REPO)}/` (pretrain.json, sanity.json, probe.json, outcome.json, run.log).", ""]
    (res / "outcome.json").write_text(json.dumps({"outcome": oc, "clause": clause, **det}, indent=1))
    dest = REPO / "results" / f"world_model_m1_v3{sfx}.md"
    dest.write_text("\n".join(L))
    print(f"wrote {dest}: {oc}")


if __name__ == "__main__":
    main()
