"""Renders results/world_model_m2_v3.md (docs/world_model_m2_protocol_v3.md): world-model start vs random start for the
three single-objective contrastive specialists, with the pre-registered Faster / Better criteria, references, curves,
trunk drift and costs.

    python tools/analyze_world_model_m2_v3.py [--seeds 111] [--smoke]
"""
from __future__ import annotations
import argparse, json, sys
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt                                     # noqa: E402

REPO = Path(__file__).resolve().parents[1]
OBJ = {"m": ("Makespan", "makespan", "min"), "c": ("Carbon", "carbon", "kg CO2e"), "t": ("Tardiness", "tardiness", "min")}
ARMS = {"ctrl": "random start", "wm": "world-model start"}
CPSAT_POINT = {"m": "mk", "c": "carbon", "t": "tard"}


def label(o, arm):
    return f"{OBJ[o][0]} specialist, {ARMS[arm]}"


def first_reach(val, target):
    """(update, train_seconds) of the first validation entry with value <= target, else None."""
    for e in val:
        if e["selection_metric"] <= target + 1e-12:
            return e["update"], e["train_seconds"]
    return None


def load_run(res, name, split):
    d = res / "runs" / name
    if not (d / "done.json").exists():
        return None
    val = json.loads((d / "valiquality.json").read_text())
    st = json.loads((d / "status.json").read_text())
    rw = json.loads((d / "reward.json").read_text())
    proc = json.loads((d / "process.json").read_text())["process_seconds"] if (d / "process.json").exists() else None
    ev = res / "eval" / f"{split}_10x5"
    g = np.load(ev / f"{name}.npz")
    smp = sorted(ev.glob(f"{name}_sample*.npz"))
    s = np.load(smp[0]) if smp else None
    best_e = next(e for e in val if e["update"] == st["best_update"])
    return {"val": val, "status": st, "best": st["best_value"], "best_update": st["best_update"],
            "stop": st["update"], "capped": st["status"] != "CONVERGED", "val0": val[0]["selection_metric"],
            "t_best": best_e["train_seconds"], "t_stop": st["train_seconds"], "proc": proc,
            "env_steps": rw[-1]["cl"]["env_steps_total"] if rw else 0,
            "drift_trunk": val[-1].get("trunk_drift"), "drift_actor": val[-1].get("actor_drift"),
            "drift_trunk_best": best_e.get("trunk_drift"),
            "greedy": {k: float(g[k].mean()) for k in ("makespan", "carbon", "tardiness", "tardy_share")},
            "sample": {k: float(s[k].mean()) for k in ("makespan", "carbon", "tardiness")} if s is not None else None}


def ms(xs, f="{:.1f}"):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "-"
    return f.format(np.mean(xs)) + (f" ± {f.format(np.std(xs))}" if len(xs) > 1 else "")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--seeds", default="111")
    ap.add_argument("--smoke", action="store_true")
    a = ap.parse_args()
    sys.path.insert(0, str(REPO / "tools"))
    import freeze_world_model_m2_v3 as F
    cfg = F.load()
    seeds = [int(s) for s in a.seeds.split(",")]
    sfx = "_smoke" if a.smoke else ""
    res, ckpt = REPO / "results" / f"world_model_m2_v3{sfx}", REPO / "checkpoints" / f"world_model_m2_v3{sfx}"
    tag = "wm2s" if a.smoke else "wm2"
    split = cfg["smoke"]["eval_split"] if a.smoke else cfg["evaluation"]["split"]
    R = {(arm, o, s): load_run(res, f"10x5+mix+bv3_{tag}_{arm}_{o}_s{s}", split)
         for arm in ARMS for o in OBJ for s in seeds}
    crit = cfg["criteria"]

    # references (read-only): committed PPO specialists, CP-SAT B1, MWKR+ECT rule
    ppo = {}
    for o in OBJ:
        for s in (111, 222, 333):
            run = f"10x5+mix+bv3_spec_{o}_s{s}"
            r = cfg["references"]["ppo_specialists"][run]
            ppo[(o, s)] = {"eval": json.loads((REPO / r["eval"]).read_text())["greedy"],
                           "sample": json.loads((REPO / r["eval"]).read_text()).get("sample100"),
                           "status": json.loads((REPO / r["status"]).read_text())}
    cp = {o: [] for o in OBJ}
    for f in sorted((REPO / cfg["references"]["cpsat_b1"]).glob("*.json")):
        p = json.loads(f.read_text())["points"]
        for o in OBJ:
            cp[o].append(p[CPSAT_POINT[o]]["final"]["exact"][OBJ[o][1]])
    diag = json.loads((REPO / "results" / "tardiness_diagnosis_v3" / "part_a_10x5.json").read_text())
    sys.path.insert(0, str(REPO / "daniel"))
    sys.argv = [sys.argv[0]]
    import benchmark_v3 as B
    ev = B.load_split("evaluation", "10x5")
    rule = {"m": float(np.mean(ev.mk_ref)), "c": float(np.mean(ev.cb_ref)), "t": diag["a3"]["rule"]["mean"]}

    L = ["# World-model M2: objective-specific specialisation from the world-model trunk (10x5)", "",
         "Protocol: `docs/world_model_m2_protocol_v3.md`. Generated by `tools/analyze_world_model_m2_v3.py`.",
         f"- **Seeds:** {', '.join(map(str, seeds))}. "
         f"{'Single seed: numbers only, no significance claims.' if len(seeds) == 1 else 'Mean ± std over seeds.'}",
         "- **Method:** single-objective contrastive fine-tuning in both arms.",
         "- **Scope:** no merging. The evaluation split is used for final values only; the reserved final-test sets "
         "were never loaded.", ""]
    if a.smoke:
        L += ["**SMOKE OUTPUT (5 updates, 3 development instances): not results.**", ""]
    L += ["## Setup", "",
          "**What every specialist shares:** each is DANIEL trained with single-objective contrastive fine-tuning:",
          "- per instance, K = 8 sampled schedules;",
          "- pairs = better on the specialist's own objective (normalised per instance) by more than 0.01;",
          "- DPO-style loss against the frozen start network;",
          "- β 0.1, gradient clip 1.0, learning rate 3e-4, 20 instances per update, resampled every 20 updates;",
          "- the SD2 generator stream (the same instance stream as the committed PPO specialists for the same seed).",
          "",
          "**The only difference between the arms is the starting network:**",
          "- **Random start:** DANIEL after `setup_seed(seed)`. All three objectives start from copies of the same file.",
          "- **World-model start:** the same network with its trunk (`feature_exact`) replaced by the M1 world-model "
          "trunk. Actor and critic are identical to the random start.", "",
          "**Training details:**",
          "- The trunk is trainable in both arms, with the same learning rate.",
          "- Validation every 50 updates on the 18 v3 validation instances. The validation value is the specialist's "
          "objective divided by its reference (MK/MKref, C/Cref, T/Tref), lower is better, the same value the PPO "
          "specialists were selected on.",
          f"- **Stopping rule:** {cfg['rule']['statement']}.", ""]

    # ------------------------------------------------------------------ criteria
    faster, better = {}, {}
    for o in OBJ:
        f_s, b_s = [], []
        for s in seeds:
            c, w = R[("ctrl", o, s)], R[("wm", o, s)]
            if not (c and w):
                continue
            hit = first_reach(w["val"], c["best"])
            f_s.append(None if hit is None else (hit[0] / c["best_update"] if c["best_update"] else float("inf")))
            b_s.append((c["greedy"][OBJ[o][1]] - w["greedy"][OBJ[o][1]]) / c["greedy"][OBJ[o][1]])
        faster[o], better[o] = f_s, b_s
    f_yes = [o for o in OBJ if faster[o] and all(x is not None for x in faster[o])
             and np.mean(faster[o]) <= crit["faster"]["ratio"]]
    b_yes = [o for o in OBJ if better[o] and np.mean(better[o]) >= crit["better"]["margin"]]
    L += ["## Answers to the pre-registered questions", "",
          "| Objective | Faster? (world-model updates to reach the random start's best, as a share of the random start's updates to its best; yes if ≤ 70%) | Better? (final evaluation value, improvement over the random start; yes if ≥ 5%) |",
          "|---|---|---|"]
    for o in OBJ:
        fs = faster[o]
        ftxt = ("not reached" if any(x is None for x in fs) else
                f"{100 * np.mean(fs):.0f}% → {'yes' if o in f_yes else 'no'}") if fs else "-"
        btxt = f"{100 * np.mean(better[o]):+.1f}% → {'yes' if o in b_yes else 'no'}" if better[o] else "-"
        L.append(f"| {OBJ[o][0]} | {ftxt} | {btxt} |")
    L += ["",
          f"- **Faster** (on at least {crit['faster']['min_objectives']} of 3 objectives): "
          f"**{'YES' if len(f_yes) >= crit['faster']['min_objectives'] else 'NO'}** ({len(f_yes)} of 3: "
          f"{', '.join(OBJ[o][0] for o in f_yes) or 'none'}).",
          f"- **Better** (on at least {crit['better']['min_objectives']} of 3 objectives): "
          f"**{'YES' if len(b_yes) >= crit['better']['min_objectives'] else 'NO'}** ({len(b_yes)} of 3: "
          f"{', '.join(OBJ[o][0] for o in b_yes) or 'none'}).",
          "- **Does the benefit generalise across objectives?** The per-objective rows above answer this directly.", ""]

    # ------------------------------------------------------------------ per objective
    L += ["## Training", "",
          "| Specialist | Validation value at update 0 | Best validation value | Update of best | Stop update | Hours to best | Hours to stop | Environment steps |",
          "|---|---|---|---|---|---|---|---|"]
    for o in OBJ:
        for arm in ARMS:
            rr = [R[(arm, o, s)] for s in seeds if R[(arm, o, s)]]
            if not rr:
                L.append(f"| {label(o, arm)} | not finished | | | | | | |"); continue
            stop = ", ".join(f"{r['stop']}{' (capped)' if r['capped'] else ''}" for r in rr)
            L.append(f"| {label(o, arm)} | {ms([r['val0'] for r in rr], '{:.4f}')} | {ms([r['best'] for r in rr], '{:.4f}')} | "
                     f"{ms([r['best_update'] for r in rr], '{:.0f}')} | {stop} | {ms([r['t_best'] / 3600 for r in rr], '{:.2f}')} | "
                     f"{ms([r['t_stop'] / 3600 for r in rr], '{:.2f}')} | {ms([r['env_steps'] for r in rr], '{:,.0f}')} |")
        ref = [ppo[(o, s)]["status"] for s in seeds]
        L.append(f"| *{OBJ[o][0]} PPO specialist, committed (reference)* | - | {ms([r['best_value'] for r in ref], '{:.4f}')} | "
                 f"{ms([r['best_update'] for r in ref], '{:.0f}')} | {', '.join(str(r['update']) for r in ref)} | - | "
                 f"{ms([r['train_seconds'] / 3600 for r in ref], '{:.2f}')} | - |")
    L += ["", "### Time to comparable performance (validation)", "",
          "Updates (and training hours) until the first validation value at or below the target; \"not reached\" if "
          "never.", "",
          "| Objective | Random start reaches world-model start's best | World-model start reaches random start's best | Random start reaches the PPO specialist's best | World-model start reaches the PPO specialist's best |",
          "|---|---|---|---|---|"]

    def reach(r, target):
        h = first_reach(r["val"], target)
        return "not reached" if h is None else f"{h[0]} ({h[1] / 3600:.2f} h)"
    for o in OBJ:
        for s in seeds:
            c, w = R[("ctrl", o, s)], R[("wm", o, s)]
            if not (c and w):
                continue
            pb = ppo[(o, s)]["status"]["best_value"]
            L.append(f"| {OBJ[o][0]}{f' (s{s})' if len(seeds) > 1 else ''} | {reach(c, w['best'])} | {reach(w, c['best'])} | "
                     f"{reach(c, pb)} | {reach(w, pb)} |")
    L += ["", "### How far the trunk moved", "",
          "Relative distance from the starting weights, ‖θ − θ₀‖ / ‖θ₀‖, at the best checkpoint and at the stop.", "",
          "| Specialist | Trunk at best | Trunk at stop | Actor at stop |", "|---|---|---|---|"]
    for o in OBJ:
        for arm in ARMS:
            rr = [R[(arm, o, s)] for s in seeds if R[(arm, o, s)]]
            if rr:
                L.append(f"| {label(o, arm)} | {ms([r['drift_trunk_best'] for r in rr], '{:.3f}')} | "
                         f"{ms([r['drift_trunk'] for r in rr], '{:.3f}')} | {ms([r['drift_actor'] for r in rr], '{:.3f}')} |")

    # ------------------------------------------------------------------ evaluation
    n_eval = cfg["smoke"]["eval_first"] if a.smoke else cfg["evaluation"]["instances"]
    L += ["", f"## Final evaluation ({split} split, {n_eval} instances, best checkpoint)", "",
          "Raw means over instances; lower is better. Greedy is the primary value; best of 100 samples is shown for "
          "context.", ""]
    for o in OBJ:
        k, unit = OBJ[o][1], OBJ[o][2]
        L += [f"### {OBJ[o][0]} ({unit})", "",
              "| Specialist | Greedy: makespan | Greedy: carbon | Greedy: tardiness | Greedy: jobs late | Best of 100: own objective | Own objective vs PPO specialist (s111) |",
              "|---|---|---|---|---|---|---|"]
        for arm in ARMS:
            rr = [R[(arm, o, s)] for s in seeds if R[(arm, o, s)]]
            if not rr:
                continue
            p111 = ppo[(o, 111)]["eval"][k]
            L.append(f"| {label(o, arm)} | " + " | ".join(ms([r["greedy"][x] for r in rr]) for x in ("makespan", "carbon", "tardiness"))
                     + f" | {ms([100 * r['greedy']['tardy_share'] for r in rr], '{:.0f}%')} | "
                     f"{ms([r['sample'][k] for r in rr if r['sample']])} | "
                     f"{100 * (np.mean([r['greedy'][k] for r in rr]) - p111) / p111:+.1f}% |")
        for s_lab, ss in (("s111", [111]), ("mean of s111/222/333", [111, 222, 333])):
            e = [ppo[(o, s)]["eval"] for s in ss]; sm = [ppo[(o, s)]["sample"] for s in ss]
            L.append(f"| *PPO specialist, committed ({s_lab})* | " + " | ".join(f"{np.mean([x[y] for x in e]):.1f}" for y in
                                                                             ("makespan", "carbon", "tardiness"))
                     + f" | {100 * np.mean([x['tardy_share'] for x in e]):.0f}% | {np.mean([x[k] for x in sm]):.1f} | - |")
        L += [f"| *CP-SAT single-objective (B1, 100 instances)* | | | | | | own objective {np.mean(cp[o]):.1f} |",
              f"| *MWKR+ECT reference rule* | | | | | | own objective {rule[o]:.1f} |", ""]

    # ------------------------------------------------------------------ figures
    fig_dir = res / "figures"; fig_dir.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(2, 3, figsize=(15, 8))
    for j, o in enumerate(OBJ):
        for arm, col in (("ctrl", "#7a7a7a"), ("wm", "#1f6fb4")):
            for s in seeds:
                r = R[(arm, o, s)]
                if r:
                    u = [e["update"] for e in r["val"]]
                    ax[0, j].plot(u, [e["selection_metric"] for e in r["val"]], color=col, lw=1.3,
                                  label=ARMS[arm] if s == seeds[0] else None)
                    ax[1, j].plot(u, [e.get("trunk_drift", np.nan) for e in r["val"]], color=col, lw=1.3,
                                  label=ARMS[arm] if s == seeds[0] else None)
        ax[0, j].axhline(np.mean([ppo[(o, s)]["status"]["best_value"] for s in seeds]), color="#c0392b", ls="--", lw=1,
                         label="PPO specialist best")
        ax[0, j].set_title(f"{OBJ[o][0]}: validation value (lower is better)"); ax[0, j].set_xlabel("update")
        ax[1, j].set_title(f"{OBJ[o][0]}: trunk drift ‖θ−θ₀‖/‖θ₀‖"); ax[1, j].set_xlabel("update")
        ax[0, j].legend(fontsize=8); ax[1, j].legend(fontsize=8)
    fig.tight_layout(); fig.savefig(fig_dir / "curves_updates.png", dpi=110); plt.close(fig)
    fig, ax = plt.subplots(1, 3, figsize=(15, 4))
    for j, o in enumerate(OBJ):
        for arm, col in (("ctrl", "#7a7a7a"), ("wm", "#1f6fb4")):
            for s in seeds:
                r = R[(arm, o, s)]
                if r:
                    ax[j].plot([e["train_seconds"] / 3600 for e in r["val"]], [e["selection_metric"] for e in r["val"]],
                               color=col, lw=1.3, label=ARMS[arm] if s == seeds[0] else None)
        ax[j].set_title(f"{OBJ[o][0]}: validation value vs training hours"); ax[j].set_xlabel("hours"); ax[j].legend(fontsize=8)
    fig.tight_layout(); fig.savefig(fig_dir / "curves_time.png", dpi=110); plt.close(fig)
    L += ["## Curves", "", "![validation and trunk drift vs updates](world_model_m2_v3" + sfx + "/figures/curves_updates.png)", "",
          "![validation vs training hours](world_model_m2_v3" + sfx + "/figures/curves_time.png)", ""]

    # ------------------------------------------------------------------ costs
    wc = cfg["world_model_cost"]
    pre = json.loads((REPO / wc["pretrain"]).read_text()); dat = json.loads((REPO / wc["data"]).read_text())
    tot = {arm: sum(R[(arm, o, s)]["t_stop"] for o in OBJ for s in seeds if R[(arm, o, s)]) for arm in ARMS}
    L += ["## Costs", "",
          f"- **Specialist training, all objectives and seeds:** random start {tot['ctrl'] / 3600:.2f} h, world-model "
          f"start {tot['wm'] / 3600:.2f} h. Runs shared one GPU, {len(seeds) * 6} runs in up to 3 parallel slots, so "
          "wall-clock is approximate and updates are the primary measure.",
          f"- **World-model pretraining, reported separately (M1, paid once for all objectives):** "
          f"{dat['seconds'] / 3600:.2f} h data generation (CPU) + {pre['seconds'] / 3600:.2f} h pretraining (GPU).", ""]

    # ------------------------------------------------------------------ files
    sums_f = ckpt / "SHA256SUMS.json"
    sums = json.loads(sums_f.read_text()) if sums_f.exists() else {}
    L += ["## Files", "", f"- **Checkpoints** (`{ckpt.relative_to(REPO)}/`, SHA-256 in `SHA256SUMS.json`): the two "
          "starting bases per seed, and the start and best checkpoints of every specialist, ready for later merging:"]
    L += [f"  - `{k}`: `{v[:16]}…`" for k, v in sums.items()]
    L += [f"- **Runs:** `{res.relative_to(REPO)}/runs/`; **evaluations:** `{res.relative_to(REPO)}/eval/`.",
          f"- **World-model trunk:** `{cfg['world_model_trunk']['path']}` (`{cfg['world_model_trunk']['sha256'][:16]}…`).", ""]
    out = REPO / "results" / f"world_model_m2_v3{sfx}.md"
    out.write_text("\n".join(L))
    (res / "criteria.json").write_text(json.dumps({"faster": {o: faster[o] for o in OBJ}, "better": {o: better[o] for o in OBJ},
                                                   "faster_yes": f_yes, "better_yes": b_yes}, indent=1))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
